function getInitialLanguage(): LanguageCode {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (languageOptions.some((option) => option.code === saved)) return saved as LanguageCode
  } catch {
    // Storage may be unavailable in private browsing; English is the safe default.
  }
  return 'en'
}

